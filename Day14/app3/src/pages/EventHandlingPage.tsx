import React from 'react'

function EventHandlingPage() {

    const handleThirdButtonClick = () => {
        console.log('Third button click event')
    }

    return (
        <div>
            <h1>Handle the button click events</h1>

            <button onClick={() => { console.log('First button clicked') }}>first button</button>

            <button onClick={() => {
                console.log('This is an onClick event')
                console.log('generated by second button')
            }}>second button</button>

            <button onClick={handleThirdButtonClick}>third button</button>
        </div>
    )
}

export default EventHandlingPage
